export function isolatedToolEnvironment(source, runDirectory) {
  if (!runDirectory || !path.isAbsolute(runDirectory)) throw new Error("An isolated absolute run directory is required.");
  const keys = ["PATH", "HOME", "USER", "LOGNAME", "SHELL", "TMPDIR", "TMP", "TEMP", "JAVA_HOME", "LANG", "LC_ALL", "TZ", "CI", "PLAYWRIGHT_BROWSERS_PATH"];
  return {
    ...Object.fromEntries(keys.filter((key) => source[key] !== undefined).map((key) => [key, source[key]])), DEBUG: "",
    XDG_CONFIG_HOME: path.join(runDirectory, "config"), CLOUDSDK_CONFIG: path.join(runDirectory, "gcloud"),
    // An explicitly nonexistent credential path makes ADC fail closed instead
    // of discovering the operator's real ~/.config/gcloud credentials. The
    // empty XDG config also prevents Firebase CLI from exporting login tokens.
    GOOGLE_APPLICATION_CREDENTIALS: path.join(runDirectory, "credentials-disabled.json"),
    FIREBASE_CLI_DISABLE_AUTOUPDATE: "true"
  };
}

export function isIsolatedFunctionSource(file) {
  const parts = file.split("/");
  return parts[0] === "functions" && parts.length > 1
    && !parts.some((part) => part.startsWith(".") || part === "node_modules")
    && (/\.(?:js|cjs)$/.test(file) || ["functions/package.json", "functions/package-lock.json", "functions/data/starterCatalogPacks.json"].includes(file));
}
