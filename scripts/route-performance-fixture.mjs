export function assertRouteFixtureScope(env = process.env) {
  if (env.GCLOUD_PROJECT !== EMULATORS.projectId
    || env.FIREBASE_AUTH_EMULATOR_HOST !== EMULATORS.authHost
    || env.FIRESTORE_EMULATOR_HOST !== EMULATORS.firestoreHost) {
    throw new Error("Route performance writes require the exact isolated demo project and emulator ports.");
  }
  assertE2EEmulatorSafety({ projectId: env.GCLOUD_PROJECT, authHost: env.FIREBASE_AUTH_EMULATOR_HOST, firestoreHost: env.FIRESTORE_EMULATOR_HOST });
}

