#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import { spawnSync } from "node:child_process";

function readArg(name) {
  const index = process.argv.indexOf(name);
  return index >= 0 ? String(process.argv[index + 1] || "").trim() : "";
}

function hasFlag(name) {
  return process.argv.includes(name);
}

function runFirebase(args) {
  const command = process.platform === "win32" ? "npx.cmd" : "npx";
  const result = spawnSync(command, ["firebase-tools", ...args, "--json"], {
    cwd: process.cwd(),
    encoding: "utf8"
  });
  if (result.status !== 0) {
    throw new Error("Firebase CLI lookup failed. Confirm that the CLI is authenticated for the requested project.");
  }
  return JSON.parse(result.stdout);
}

const projectId = readArg("--project");
if (!/^[a-z0-9][a-z0-9-]{4,28}[a-z0-9]$/.test(projectId)) {
  throw new Error("Pass an explicit Firebase project id with --project.");
}
const outputFile = ".env.local";
const outputPath = path.resolve(process.cwd(), outputFile);
const replaceRequested = hasFlag("--replace");
const replaceConfirmation = readArg("--confirm");
const expectedConfirmation = `REPLACE ${outputFile} FOR ${projectId}`;

if (fs.existsSync(outputPath)) {
  if (!replaceRequested) {
    throw new Error(
      `${outputFile} already exists. Refusing to overwrite it; review the file or rerun with --replace and the exact confirmation token.`
    );
  }
  if (replaceConfirmation !== expectedConfirmation) {
    throw new Error(`Replacing ${outputFile} requires --confirm "${expectedConfirmation}".`);
  }
}

const appsPayload = runFirebase(["apps:list", "--project", projectId]);
const apps = Array.isArray(appsPayload?.result)
  ? appsPayload.result
  : Array.isArray(appsPayload?.result?.apps)
    ? appsPayload.result.apps
    : [];
const webApps = apps.filter((app) => String(app?.platform || "").toUpperCase() === "WEB");
if (webApps.length !== 1) {
  throw new Error(`Expected exactly one Firebase web app in ${projectId}; found ${webApps.length}.`);
}

const appId = String(webApps[0]?.appId || "").trim();
const configPayload = runFirebase([
  "apps:sdkconfig",
  "WEB",
  appId,
  "--project",
  projectId
]);
const config = configPayload?.result?.sdkConfig || {};
const requiredConfig = [
  "apiKey",
  "authDomain",
  "projectId",
  "storageBucket",
  "messagingSenderId",
  "appId"
];
const missing = requiredConfig.filter((key) => !String(config[key] || "").trim());
if (missing.length) {
  throw new Error(`Firebase web configuration is missing: ${missing.join(", ")}.`);
}
if (String(config.projectId).trim() !== projectId) {
  throw new Error("Firebase SDK config project does not match the requested project.");
}

const lines = [
  "# Generated by npm run env:local:firebase. This file is ignored by git.",
  "# Firebase web keys identify the app; provider secrets belong only in functions/.env.<project>.",
  "VITE_ALLOW_LOCAL_CATALOG_FALLBACK=false",
  "VITE_BASE_DOMAIN=mbmapps.com",
  "VITE_APP_HOST=quotepilot.mbmapps.com",
  "VITE_APP_URL=https://quotepilot.mbmapps.com/app",
  "VITE_DEFAULT_ORGANIZATION_ID=",
  `VITE_FIREBASE_API_KEY=${String(config.apiKey).trim()}`,
  `VITE_FIREBASE_APP_ID=${String(config.appId).trim()}`,
  `VITE_FIREBASE_AUTH_DOMAIN=${String(config.authDomain).trim()}`,
  "VITE_FIREBASE_FUNCTIONS_REGION=us-central1",
  `VITE_FIREBASE_MESSAGING_SENDER_ID=${String(config.messagingSenderId).trim()}`,
  `VITE_FIREBASE_PROJECT_ID=${projectId}`,
  `VITE_FIREBASE_STORAGE_BUCKET=${String(config.storageBucket).trim()}`,
  "VITE_USE_FIREBASE_EMULATORS=false",
  ""
];

fs.writeFileSync(outputPath, lines.join("\n"), {
  encoding: "utf8",
  mode: 0o600,
  flag: replaceRequested ? "w" : "wx"
});
fs.chmodSync(outputPath, 0o600);

console.log(`Local Firebase environment written to ${outputFile} for ${projectId}.`);
